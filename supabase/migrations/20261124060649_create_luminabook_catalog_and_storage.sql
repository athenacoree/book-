create table if not exists public.luminabook_catalog_items (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  title text not null,
  author text not null default '',
  description text not null default '',
  item_type text not null check (item_type in ('book', 'game', 'other')),
  file_format text not null check (file_format in ('epub', 'pdf', 'mobi', 'fb2', 'txt', 'html', 'zip')),
  storage_path text not null,
  cover_path text,
  language_code text,
  subjects text[] not null default '{}',
  file_size_bytes bigint not null default 0 check (file_size_bytes >= 0),
  download_count bigint not null default 0 check (download_count >= 0),
  is_published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists luminabook_catalog_published_type_created_idx
  on public.luminabook_catalog_items (item_type, created_at desc)
  where is_published = true;

create index if not exists luminabook_catalog_title_search_idx
  on public.luminabook_catalog_items using gin (to_tsvector('simple', title || ' ' || author))
  where is_published = true;

alter table public.luminabook_catalog_items enable row level security;

drop policy if exists "Published LuminaBook catalog is readable" on public.luminabook_catalog_items;
create policy "Published LuminaBook catalog is readable"
  on public.luminabook_catalog_items
  for select
  to anon, authenticated
  using (is_published = true);

grant select on public.luminabook_catalog_items to anon, authenticated;

